describe('copy for not-applicable, untiered and run notes', () => {
  it.each(NEW_KEYS)('has English and Japanese text for %s', (key) => {
    expect(translate(key, 'en')).not.toBe(key);
    expect(translate(key, 'ja')).not.toBe(key);
    // Templates that are language-neutral (placeholders only, or backend free-text) stay identical.
    if (key !== 'runNotes.code.free-text' && key !== 'overview.configured.metricTitle') {
      expect(translate(key, 'ja')).not.toBe(translate(key, 'en'));
    }
  });

  it('keeps the same placeholders in both languages', () => {
    const placeholders = (text: string) => [...text.matchAll(/\{\{(\w+)\}\}/g)].map((match) => match[1]).sort();

    for (const key of NEW_KEYS) {
      expect(placeholders(translate(key, 'ja'))).toEqual(placeholders(translate(key, 'en')));
    }
  });
});
